"""SYNTHETIC review generation for the offline demonstration and tests ONLY.

These are not human judgements. Every generated review uses a ``SYNTHETIC-``
reviewer ID and ``reviewer_provenance = synthetic_fixture``; the import step
rejects them unless explicitly allowed, and all downstream reports label any
result built on them as synthetic. The rule is mechanical: a chrF threshold
against fixture references plus a deterministic disagreement for the second
synthetic reviewer, so that agreement and calibration code has something to
compute on.
"""

from __future__ import annotations

import hashlib
from datetime import date
from typing import Any

from ..models.enums import (
    ErrorCategory,
    ReviewerProvenance,
    ReviewJudgement,
    Severity,
    TargetLanguage,
)
from ..models.passage import Passage
from ..models.review import HumanReview, MQMError
from .metrics import chrf


def _h(*parts: object) -> int:
    return int(hashlib.sha256("|".join(map(str, parts)).encode()).hexdigest()[:8], 16)


def simulate_reviews(
    items: list[dict[str, Any]],
    passages: dict[str, Passage],
    *,
    package_id: str,
    reviewer_ids: tuple[str, ...] = ("SYNTHETIC-REVIEWER-1", "SYNTHETIC-REVIEWER-2"),
    on: date | None = None,
    threshold: float = 80.0,
) -> list[dict[str, Any]]:
    """Return JSONL-ready review rows for every item and synthetic reviewer."""
    rows: list[dict[str, Any]] = []
    day = (on or date.today()).isoformat()
    for item in items:
        p = passages[item["passage_id"]]
        for idx, reviewer in enumerate(reviewer_ids):
            if not reviewer.upper().startswith("SYNTHETIC"):
                raise ValueError("simulated reviewers must have SYNTHETIC- IDs")
            judgements: dict[str, str] = {}
            errors: list[dict[str, Any]] = []
            for lang, field in (
                (TargetLanguage.MODERN_FRENCH, "translation_fr"),
                (TargetLanguage.ENGLISH, "translation_en"),
            ):
                hyp = item.get(field) or ""
                refs = [r.text for r in p.references_for(lang)]
                score = chrf(hyp, refs) if hyp and refs else 0.0
                ok = score >= threshold
                # Second synthetic reviewer disagrees on borderline cases deterministically.
                if (
                    idx > 0
                    and abs(score - threshold) < 12
                    and _h(item["review_item_id"], lang) % 3 == 0
                ):
                    ok = not ok
                judgements[str(lang)] = str(
                    ReviewJudgement.ACCEPTABLE if ok else ReviewJudgement.UNACCEPTABLE
                )
                if not ok:
                    cat = (
                        ErrorCategory.OMISSION
                        if len(hyp) < 0.85 * len(refs[0] if refs else hyp)
                        else ErrorCategory.MISTRANSLATION
                    )
                    errors.append(MQMError(category=cat, severity=Severity.MAJOR, target_language=lang,
                                           note=f"SYNTHETIC: chrF {score:.1f} below {threshold}").model_dump(mode="json"))  # fmt: skip
                elif score < 95:
                    errors.append(MQMError(category=ErrorCategory.FLUENCY, severity=Severity.MINOR, target_language=lang,
                                           note=f"SYNTHETIC: chrF {score:.1f}").model_dump(mode="json"))  # fmt: skip
            review = HumanReview(
                review_id=f"{package_id}:{item['review_item_id']}:{reviewer}",
                review_item_id=item["review_item_id"], package_id=package_id, reviewer_id=reviewer,
                reviewer_provenance=ReviewerProvenance.SYNTHETIC_FIXTURE, reviewed_on=date.fromisoformat(day),
                judgement_fr=ReviewJudgement(judgements["fr"]), judgement_en=ReviewJudgement(judgements["en"]),
                errors=[MQMError.model_validate(e) for e in errors],
                ambiguity_flag=bool(p.ambiguities), reviewer_confidence=3,
                comments="SYNTHETIC review generated by a chrF rule for software demonstration; not a human judgement.",
            )  # fmt: skip
            rows.append(review.model_dump(mode="json"))
    return rows
